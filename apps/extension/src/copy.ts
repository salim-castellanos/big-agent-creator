export function phrase(lang: Lang | undefined, message: string): string {
  if (lang !== "es" || !message) return message;
  const exact = sentences[message];
  if (exact) return exact;
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^No MCP named (.+) is on this canvas\.$/, (match) => `No hay un Servicio llamado ${match[1]} en este lienzo.`],
    [/^(.+) is empty\. Set it in Secrets\.$/, (match) => `${match[1]} está vacío. Ponlo en Secretos.`],
    [/^(.+) imports "zod"\. Generated files use import \* as z from "zod\/v4"\.$/, (match) => `${match[1]} importa "zod". Los archivos generados usan import * as z from "zod/v4".`],
    [/^Tunnel ready at (\S+)\. Register webhook next\. Leave this session open\.$/, (match) => `Túnel listo en ${match[1]}. Sigue con Registrar webhook. Deja esta sesión abierta.`],
    [/^Loaded (.+)\. (This folder was kept in \.keep\/original\.|\.keep\/original was already there and was not replaced\.)( Your \.env stayed\.)?$/, (match) => `Cargado ${match[1]}. ${phrase("es", match[2])}${match[3] ? phrase("es", match[3]) : ""}`],
    [/^Cloudflare Tunnel is not available\. Install it with winget install --id Cloudflare\.cloudflared, or paste an https address you already have\.(?: (.*))?$/, (match) => `Cloudflare Tunnel no está disponible. Instálalo con winget install --id Cloudflare.cloudflared, o pega una dirección https que ya tengas.${match[1] ? ` ${match[1]}` : ""}`],
  ];
  for (const [pattern, render] of patterns) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}

